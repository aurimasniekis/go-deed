#!/usr/bin/env python3
"""S3-compatibility validation driver (stdlib only). Invoked by scripts/validate/s3.sh once per implementation:

  s3_driver.py run      run Deed's S3 integration tests (go test -json) and an end-to-end backup → list → verify →
                        restore with the deed CLI, retention pruning, an interrupted multipart upload, ListObjectsV2
                        paging and SSE-S3 handling against the S3 server in $S3_ENDPOINT; merges into
                        $VAL_DIR/results.json
  s3_driver.py summary  print the per-implementation table from results.json and exit 1 when a step failed

Every step prints PASS/FAIL with evidence. Credentials are generated by s3.sh into $VAL_DIR/secrets (0600)."""
import datetime, hashlib, hmac, json, os, subprocess, sys, time, urllib.error, urllib.parse, urllib.request
import xml.etree.ElementTree as ET

VAL = os.environ["VAL_DIR"]
SEC = os.path.join(VAL, "secrets")
BIN = os.path.join(VAL, "bin")
ROOT = os.environ.get("VAL_ROOT", os.getcwd())
IMPL = os.environ.get("S3_IMPL", "")
results = []


def secret(name):
    return open(os.path.join(SEC, name)).read().strip()


class S3:
    """A minimal path-style S3 client with AWS Signature V4 (independent of minio-go, which Deed uses)."""

    def __init__(self, endpoint, access, secret_key, region):
        self.endpoint, self.access, self.secret, self.region = endpoint, access, secret_key, region

    def request(self, method, bucket="", key="", query=None, body=b"", headers=None):
        q = query or {}
        path = "/" + bucket + ("/" + key if key else ("/" if bucket else ""))
        cpath = urllib.parse.quote(path, safe="/~")
        cquery = "&".join(f"{urllib.parse.quote(k, safe='~')}={urllib.parse.quote(str(v), safe='~')}" for k, v in sorted(q.items()))
        now = datetime.datetime.now(datetime.timezone.utc)
        amzdate, date = now.strftime("%Y%m%dT%H%M%SZ"), now.strftime("%Y%m%d")
        phash = hashlib.sha256(body).hexdigest()
        h = {"host": self.endpoint, "x-amz-date": amzdate, "x-amz-content-sha256": phash}
        h.update({k.lower(): v for k, v in (headers or {}).items()})
        signed = ";".join(sorted(h))
        creq = "\n".join([method, cpath, cquery, "".join(f"{k}:{str(h[k]).strip()}\n" for k in sorted(h)), signed, phash])
        scope = f"{date}/{self.region}/s3/aws4_request"
        sts = "\n".join(["AWS4-HMAC-SHA256", amzdate, scope, hashlib.sha256(creq.encode()).hexdigest()])
        k = ("AWS4" + self.secret).encode()
        for part in (date, self.region, "s3", "aws4_request"):
            k = hmac.new(k, part.encode(), hashlib.sha256).digest()
        sig = hmac.new(k, sts.encode(), hashlib.sha256).hexdigest()
        h["authorization"] = f"AWS4-HMAC-SHA256 Credential={self.access}/{scope}, SignedHeaders={signed}, Signature={sig}"
        del h["host"]
        url = f"http://{self.endpoint}{cpath}" + (f"?{cquery}" if cquery else "")
        req = urllib.request.Request(url, method=method, data=body if method in ("PUT", "POST") else None, headers=h)
        try:
            resp = urllib.request.urlopen(req, timeout=60)
            return resp.status, dict(resp.headers), resp.read()
        except urllib.error.HTTPError as e:
            return e.code, dict(e.headers), e.read()

    def ok(self, *a, **kw):
        code, hdrs, body = self.request(*a, **kw)
        if code >= 300:
            raise AssertionError(f"S3 {a[0]} {a[1:3]}: HTTP {code}: {body[:400]!r}")
        return hdrs, body

    def make_bucket(self, bucket):
        deadline = time.time() + 60
        while True:
            try:
                code, _, body = self.request("PUT", bucket)
            except OSError as e:
                code, body = 0, str(e).encode()
            if code == 200:
                return
            if time.time() > deadline:
                raise AssertionError(f"create bucket {bucket}: HTTP {code}: {body[:300]!r}")
            time.sleep(0.5)

    def list_keys(self, bucket, prefix):
        keys, token = [], None
        while True:
            q = {"list-type": "2", "prefix": prefix}
            if token:
                q["continuation-token"] = token
            _, body = self.ok("GET", bucket, query=q)
            root = ET.fromstring(body)
            ns = root.tag.split("}")[0] + "}" if root.tag.startswith("{") else ""
            keys += [c.findtext(f"{ns}Key") for c in root.findall(f"{ns}Contents")]
            if root.findtext(f"{ns}IsTruncated") != "true":
                return keys
            token = root.findtext(f"{ns}NextContinuationToken")

    def uploads(self, bucket, prefix):
        _, body = self.ok("GET", bucket, query={"uploads": "", "prefix": prefix})
        root = ET.fromstring(body)
        ns = root.tag.split("}")[0] + "}" if root.tag.startswith("{") else ""
        return [(u.findtext(f"{ns}Key"), u.findtext(f"{ns}UploadId")) for u in root.findall(f"{ns}Upload")]

    def start_upload(self, bucket, key, part=b""):
        _, body = self.ok("POST", bucket, key, query={"uploads": ""})
        root = ET.fromstring(body)
        ns = root.tag.split("}")[0] + "}" if root.tag.startswith("{") else ""
        uid = root.findtext(f"{ns}UploadId")
        if part:
            self.ok("PUT", bucket, key, query={"partNumber": "1", "uploadId": uid}, body=part)
        return uid


def step(title):
    def deco(fn):
        def wrapped(*a):
            t0 = time.time()
            try:
                ev = fn(*a) or {}
                results.append({"step": title, "ok": True, "evidence": ev, "seconds": round(time.time() - t0, 1)})
                print(f"PASS [{IMPL}] {title}\n        {json.dumps(ev)[:1500]}")
                return True
            except Exception as ex:  # noqa: BLE001 — every failure is reported, then the run continues where possible
                results.append({"step": title, "ok": False, "error": str(ex)[:2000], "seconds": round(time.time() - t0, 1)})
                print(f"FAIL [{IMPL}] {title}\n        {ex}")
                return False
        return wrapped
    return deco


def deed(*args, check=True, timeout=300):
    p = subprocess.run([os.path.join(BIN, "deed"), *args], capture_output=True, text=True, timeout=timeout)
    if check and p.returncode != 0:
        raise AssertionError(f"deed {' '.join(args[:2])}: exit {p.returncode}: {p.stderr.strip()[-800:]}")
    return p


def last_error(stderr):
    lines = [l for l in stderr.strip().splitlines() if l.startswith("deed: ")]
    return lines[-1] if lines else stderr.strip()[-400:]


class Run:
    def __init__(self):
        self.endpoint = os.environ["S3_ENDPOINT"]
        self.access, self.secret = secret(f"{IMPL}-access"), secret(f"{IMPL}-secret")
        self.region = os.environ.get("S3_SIGN_REGION") or "us-east-1"  # what this driver signs with
        self.cfg_region = os.environ.get("S3_CONFIG_REGION", "")  # what Deed is configured with ("" = discover)
        self.sse = os.environ.get("S3_SSE", "")  # on: SSE-S3 applied; off: rejected; ignored: accepted, not applied
        self.s3 = S3(self.endpoint, self.access, self.secret, self.region)
        self.dir = os.path.join(VAL, IMPL)
        os.makedirs(self.dir, mode=0o700, exist_ok=True)
        self.bucket = f"deed-val-{IMPL}-{os.urandom(3).hex()}"
        self.prefix = "deed/"
        self.state = {}

    # --- configuration ---------------------------------------------------------------------------------------------
    def config(self, name, data_dir, kek, sse, region=None):
        region = self.cfg_region if region is None else region
        y = f"""mode: development
data_dir: {data_dir}
public_url: http://127.0.0.1:1
kek: {{source: file, file: {kek}}}
http: {{listen: 127.0.0.1:0}}
management: {{listen: 127.0.0.1:0}}
log: {{level: warn, format: json}}
backup:
  enabled: false
  keep_daily: 1
  keep_weekly: 0
  keep_monthly: 0
  recipients: ["{open(os.path.join(SEC, 'age-recipient.txt')).read().strip()}"]
  s3: {{endpoint: "{self.endpoint}", bucket: {self.bucket}, prefix: "{self.prefix}", region: "{region}", access_key_id: {self.access},
       secret_access_key_file: {os.path.join(SEC, IMPL + '-secret')}, insecure: true, lookup: path, sse: {'true' if sse else 'false'}}}
"""
        path = os.path.join(self.dir, name)
        with open(os.open(path, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600), "w") as f:
            f.write(y)
        return path

    def run_all(self):
        self.go_tests()
        if not self.setup():
            return
        self.wrong_region()
        self.sse_first_backup()
        self.plant()
        self.retention()
        self.list_verified()
        self.verify()
        self.restore()

    # --- go test ---------------------------------------------------------------------------------------------------
    @step("go test TestMinIO|TestS3Compat|TestS3Backend against the server")
    def go_tests(self):
        q = {}
        if os.environ.get("S3_TEST_REGION"):
            q["region"] = os.environ["S3_TEST_REGION"]
        if self.sse in ("on", "off"):
            q["sse"] = self.sse
        if os.environ.get("S3_VHOST"):
            q["vhost"] = os.environ["S3_VHOST"]
        url = f"http://{urllib.parse.quote(self.access)}:{urllib.parse.quote(self.secret)}@{self.endpoint}" + ("?" + urllib.parse.urlencode(q) if q else "")
        env = dict(os.environ, DEED_TEST_S3=url)
        p = subprocess.run(["go", "test", "-count=1", "-json", "-run", "^(TestMinIO|TestS3Compat|TestS3Backend)$", "./internal/backup/", "./internal/tfimport/"],
                           cwd=ROOT, env=env, capture_output=True, text=True, timeout=900)
        outcome, logs = {}, {}
        for line in p.stdout.splitlines():
            try:
                ev = json.loads(line)
            except ValueError:
                continue
            t = ev.get("Test")
            if not t:
                continue
            if ev.get("Action") in ("pass", "fail", "skip"):
                outcome[t] = ev["Action"]
            elif ev.get("Action") == "output" and ".go:" in ev.get("Output", ""):
                logs.setdefault(t, []).append(ev["Output"].strip())
        with open(os.path.join(self.dir, "go-test.json"), "w") as f:
            f.write(p.stdout)
        notes = {t: v for t, v in logs.items() if t.split("/")[-1] in ("sse-s3", "wrong-region", "wrong-credentials") or outcome.get(t) == "fail"}
        need = ["TestMinIO", "TestS3Compat", "TestS3Backend"]
        if p.returncode != 0 or any(outcome.get(t) != "pass" for t in need):
            raise AssertionError(f"go test exit {p.returncode}: {json.dumps({k: v for k, v in outcome.items() if v != 'pass'})} {json.dumps(notes)[:1200]} "
                                 f"{p.stderr[-400:]}")
        return {"tests": outcome, "notes": notes}

    # --- deed CLI --------------------------------------------------------------------------------------------------
    @step("deed: keys, migrate, bootstrap; create the bucket through the S3 API")
    def setup(self):
        self.s3.make_bucket(self.bucket)
        kek = os.path.join(self.dir, "kek")
        if not os.path.exists(kek):
            deed("keys", "init", "-out", kek)
        self.cfg = self.config("deed.yaml", os.path.join(self.dir, "data"), kek, sse=self.sse != "off")
        self.cfg_nosse = self.config("deed-nosse.yaml", os.path.join(self.dir, "data"), kek, sse=False)
        deed("config", "check", "-config", self.cfg)
        deed("migrate", "-config", self.cfg)
        deed("admin", "bootstrap", "-config", self.cfg)
        self.state["verify_key"] = deed("backup", "verify-key", "-config", self.cfg).stdout.strip()
        return {"bucket": self.bucket, "config_region": self.cfg_region or "(empty: discovered)", "sign_region": self.region}

    @step("wrong backup.s3.region: accepted, or rejected with a hint at backup.s3.region")
    def wrong_region(self):
        cfg = self.config("deed-wrong-region.yaml", os.path.join(self.dir, "data"), os.path.join(self.dir, "kek"), sse=False, region="deed-wrong-region-1")
        p = deed("backup", "run", "-config", cfg, check=False)
        if p.returncode == 0:
            self.state.setdefault("ids", []).append(json.loads(p.stdout)["id"])
            return {"result": "accepted: the server does not check the signature region"}
        msg = last_error(p.stderr)
        assert "backup.s3.region" in msg, msg
        return {"result": "rejected", "message": msg}

    @step("first backup (SSE-S3 per the server's support; a rejection names backup.s3.sse and leaves no upload behind)")
    def sse_first_backup(self):
        ev = {}
        if self.sse == "off":
            p = deed("backup", "run", "-config", self.config("deed-sse.yaml", os.path.join(self.dir, "data"), os.path.join(self.dir, "kek"), sse=True),
                     check=False, timeout=600)
            msg = last_error(p.stderr)
            assert p.returncode != 0 and "backup.s3.sse: false" in msg, f"exit {p.returncode}: {msg}"
            left = self.s3.uploads(self.bucket, self.prefix)
            assert not left, f"incomplete uploads left by the rejected SSE backup: {left}"
            ev["sse_rejected"] = msg
            cfg = self.cfg_nosse
        else:
            cfg = self.cfg
        run = json.loads(deed("backup", "run", "-config", cfg).stdout)
        assert run["result"] == "ok", run
        self.state.setdefault("ids", []).append(run["id"])
        hdrs, _ = self.s3.ok("HEAD", self.bucket, f"{self.prefix}backups/{run['id']}/deed.db.zst.age")
        applied = {k.lower(): v for k, v in hdrs.items()}.get("x-amz-server-side-encryption", "")
        if self.sse == "on":
            assert applied == "AES256", f"SSE-S3 requested but HEAD says {applied!r}"
        ev.update({"backup_id": run["id"], "size_bytes": run["size_bytes"], "sse_requested": self.sse != "off", "sse_applied_head": applied or "(none)"})
        return ev

    @step("plant: an interrupted multipart upload, an incomplete backup and 1001 keys sorted before the backups (forces ListObjectsV2 paging)")
    def plant(self):
        p = self.prefix + "backups/"
        uid = self.s3.start_upload(self.bucket, p + "bkp_01jbzzzzzzzzzzzzzzzzzzzzzy/deed.db.zst.age", part=os.urandom(5 << 20))
        self.s3.ok("PUT", self.bucket, p + "bkp_01jbzzzzzzzzzzzzzzzzzzzzzx/deed.db.zst.age", body=b"age-ciphertext-without-a-manifest")
        for i in range(1001):
            self.s3.ok("PUT", self.bucket, f"{p}aaa-paging/{i:04d}", body=b"x")
        ups = self.s3.uploads(self.bucket, self.prefix)
        assert any(u == uid for _, u in ups), ups
        return {"upload_id": uid, "uploads_before": len(ups), "keys_under_backups": len(self.s3.list_keys(self.bucket, p))}

    @step("retention (keep_daily 1): two more backups prune every older one and abort the interrupted upload")
    def retention(self):
        for _ in range(2):
            time.sleep(1.1)
            run = json.loads(deed("backup", "run", "-config", self.cfg_nosse if self.sse == "off" else self.cfg).stdout)
            assert run["result"] == "ok", run
            self.state["ids"].append(run["id"])
        latest = self.state["ids"][-1]
        keys = self.s3.list_keys(self.bucket, self.prefix + "backups/bkp_")
        ids = sorted({k.split("/")[2] for k in keys})
        older = [i for i in self.state["ids"][:-1] if i in ids]
        assert not older, f"older backups not pruned: {older}"
        assert latest in ids, ids
        assert "bkp_01jbzzzzzzzzzzzzzzzzzzzzzx" in ids, "a fresh incomplete backup (< 24 h) must stay"
        left = self.s3.uploads(self.bucket, self.prefix)
        assert not left, f"incomplete uploads not aborted: {left}"
        return {"backups_taken": self.state["ids"], "backup_ids_in_bucket": ids, "latest_objects": sorted(k.split("/")[-1] for k in keys if latest in k),
                "uploads_after": len(left)}

    @step("deed backup list: one complete verified backup behind 1001 earlier keys, the planted one incomplete")
    def list_verified(self):
        rs = json.loads(deed("backup", "list", "-config", self.cfg, "-verify-key", self.state["verify_key"]).stdout)
        complete = [r for r in rs if r["complete"]]
        assert len(complete) == 1 and complete[0]["id"] == self.state["ids"][-1] and complete[0]["verified"], rs
        assert any(r["id"] == "bkp_01jbzzzzzzzzzzzzzzzzzzzzzx" and not r["complete"] for r in rs), rs
        return {"listed": [{k: r[k] for k in ("id", "complete", "verified", "bytes")} for r in rs]}

    @step("deed backup verify -id latest (download, hashes, decrypt, integrity_check, counts)")
    def verify(self):
        out = json.loads(deed("backup", "verify", "-config", self.cfg, "-identity", os.path.join(SEC, "age-identity.txt"),
                              "-verify-key", self.state["verify_key"], "-id", "latest").stdout)
        assert out["ok"] and out["verified_signature"] and out["kek_included"] and out["manifest"]["id"] == self.state["ids"][-1], out
        self.state["counts"] = out["counts"]
        return {"id": out["manifest"]["id"], "counts": out["counts"], "objects": [(o["name"], o["stored_size"]) for o in out["manifest"]["objects"]]}

    @step("deed restore -id latest into a fresh data directory (escrowed KEK, audit chain, counts)")
    def restore(self):
        kek = os.path.join(self.dir, "kek-restored")
        cfg = self.config("restore.yaml", os.path.join(self.dir, "restored"), kek, sse=False)
        out = json.loads(deed("restore", "-config", cfg, "-identity", os.path.join(SEC, "age-identity.txt"), "-verify-key", self.state["verify_key"],
                              "-id", "latest", "-kek-out", kek, "-yes").stdout)
        v = out["validation"]
        assert out["backup_id"] == self.state["ids"][-1] and v["audit_chain_ok"] and v["counts"] == self.state["counts"], out
        with open(os.path.join(self.dir, "kek")) as a, open(kek) as b:
            assert a.read().strip() == b.read().strip(), "restored KEK differs"
        return {"backup_id": out["backup_id"], "audit_events_verified": v["audit_events_verified"], "counts": v["counts"]}


def merge():
    path = os.path.join(VAL, "results.json")
    try:
        doc = json.load(open(path))
    except (OSError, ValueError):
        doc = {"implementations": {}}
    doc["implementations"][IMPL] = {"image": os.environ.get("S3_IMAGE"), "digest": os.environ.get("S3_DIGEST"), "version": os.environ.get("S3_VERSION"),
                                    "sse": os.environ.get("S3_SSE"), "steps": results,
                                    "finished": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())}
    doc["deed_commit"] = os.environ.get("VAL_COMMIT")
    json.dump(doc, open(path, "w"), indent=1)


def summary():
    doc = json.load(open(os.path.join(VAL, "results.json")))
    failed = 0
    print("\n== summary")
    for impl, r in doc["implementations"].items():
        ok = sum(s["ok"] for s in r["steps"])
        failed += len(r["steps"]) - ok
        print(f"{impl:<16} {r['image']:<34} {ok}/{len(r['steps'])} steps passed" +
              "".join(f"\n    FAIL {s['step']}" for s in r["steps"] if not s["ok"]))
    sys.exit(1 if failed else 0)


def main():
    if sys.argv[1:] == ["summary"]:
        summary()
        return
    Run().run_all()
    merge()
    failed = [r["step"] for r in results if not r["ok"]]
    print(f"[{IMPL}] {len(results) - len(failed)}/{len(results)} steps passed" + (f"; failed: {failed}" if failed else ""))


if __name__ == "__main__":
    main()
